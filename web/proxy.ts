import { NextRequest, NextResponse } from "next/server";
import { SESSION_COOKIE } from "@/lib/cookie-names";

// Optimistic check only (cookie presence, not signature verification) --
// real authorization is enforced by the Express API's requireRole + Postgres
// RLS on every request, regardless of what happens here.
const PUBLIC_ROUTES = ["/login"];

export function proxy(request: NextRequest): NextResponse {
  const { pathname } = request.nextUrl;
  const hasSession = request.cookies.has(SESSION_COOKIE);
  const isPublicRoute = PUBLIC_ROUTES.includes(pathname);

  if (!hasSession && !isPublicRoute) {
    const loginUrl = new URL("/login", request.url);
    loginUrl.searchParams.set("next", pathname);
    return NextResponse.redirect(loginUrl);
  }

  if (hasSession && isPublicRoute) {
    return NextResponse.redirect(new URL("/dashboard", request.url));
  }

  return NextResponse.next();
}

// Excludes API routes, Next.js internals, and any request for a static asset
// file (favicon.ico, /icon.jpg auto-generated by the app-icon convention,
// /logo.jpg, and anything else added to public/ later) -- these are fetched
// unauthenticated by the browser (e.g. on the login page itself, before any
// session cookie exists) and must never be redirected to /login.
export const config = {
  matcher: ["/((?!api|_next/static|_next/image|.*\\.(?:ico|png|jpg|jpeg|svg|webp|gif)$).*)"],
};
